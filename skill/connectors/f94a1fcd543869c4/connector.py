def call_api(df):
    """Tableau Prep entry point. Input df is a trigger row (single 'folder'-like
    column from the rewired local xlsx). We ignore it and pull from the API.
    Output: a DataFrame matching the API's records, schema-inferred.

    Coerces every output column into the dtype declared by
    `get_output_schema()`. Tableau Prep is strict: a column declared
    `prep_int()` whose actual values are floats / pandas objects /
    NaN-mixed-with-ints is rejected with "An integer type is required
    for field [X]". This applies to every fetcher branch."""
    fetcher = _DISPATCH.get(FORMAT, _fetch_json)
    out_df = fetcher()
    return _coerce_to_declared_schema(out_df)


def _coerce_to_declared_schema(df):
    """Cast each column of `df` to match what `get_output_schema()`
    declares. Maestro's compile-time schema check rejects columns
    whose actual dtype doesn't match the helper used in the schema
    (e.g. prep_int with object dtype, prep_string with datetime64).

    Without this final pass, ArcGIS' SmallInteger fields (which arrive
    as pandas float64 because they may be NaN) get declared as
    prep_int but rejected by Maestro. Same family of failure for date
    cols that round-tripped via pd.to_datetime."""
    if df is None or len(df) == 0:
        return df
    try:
        schema_df = get_output_schema()
        declared = {col: schema_df[col].iloc[0] if len(schema_df) > 0 else None
                    for col in schema_df.columns}
    except Exception:
        return df
    int_marker = type(prep_int()) if hasattr(__builtins__, "prep_int") or "prep_int" in dir() else None  # noqa: F821
    # Use the actual function references for type checks.
    INT_TY = prep_int()       # noqa: F821
    DEC_TY = prep_decimal()   # noqa: F821
    BOOL_TY = prep_bool()     # noqa: F821
    STR_TY = prep_string()    # noqa: F821
    try:
        DATE_TY = prep_date()      # noqa: F821
        DT_TY   = prep_datetime()  # noqa: F821
    except Exception:
        DATE_TY = None
        DT_TY = None

    def _is(ty, ref):
        return ref is not None and type(ty).__name__ == type(ref).__name__

    for col, ty in declared.items():
        if col not in df.columns:
            continue
        try:
            s = df[col]
            if _is(ty, INT_TY):
                # ints must be Python ints (not float). Replace NaN with 0
                # since Maestro's int wire format has no null marker on
                # this path; analysts can filter on 0 if they need to.
                df[col] = pd.to_numeric(s, errors="coerce").fillna(0).astype("int64")
            elif _is(ty, DEC_TY):
                df[col] = pd.to_numeric(s, errors="coerce")
            elif _is(ty, BOOL_TY):
                df[col] = s.astype("bool")
            elif _is(ty, STR_TY):
                df[col] = s.fillna("").astype(str) if hasattr(s, "fillna") else s.astype(str)
            # date / datetime declared columns: leave string ISO 8601 as-is
            # (Tableau accepts ISO strings under prep_date/prep_datetime).
        except Exception:
            # Don't fail the whole fetch over one column; let Maestro
            # surface the error so the user can correct the spec.
            continue
    return df


