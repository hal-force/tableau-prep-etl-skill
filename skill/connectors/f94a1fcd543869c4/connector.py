def _fetch_json() -> pd.DataFrame:
    if GRAPHQL:
        data = _http_request_json({"query": GRAPHQL_QUERY}, method="POST")
        rows = data.get("data") or data
        rows = _unwrap_json_records(rows)
        df = pd.DataFrame(rows) if isinstance(rows, list) else pd.DataFrame([{"raw": json.dumps(rows)}])
        return _apply_json_schema_coercion(df)

    if not JSON_PAGINATE:
        if JSON_HTTP_METHOD.upper() == "POST" and JSON_BODY is not None:
            doc = _http_request_json(JSON_BODY, method="POST")
        else:
            doc = _http_request_json(method="GET")
        rows = _extract_json_records(doc)
        rows = _flatten_inner_records(rows)
        df = pd.DataFrame(rows) if isinstance(rows, list) else pd.DataFrame([{"raw": json.dumps(rows)}])
        return _apply_json_schema_coercion(df)

    # Paginated walk. Treasury Fiscal Data + JSON:API style: append
    # `page[number]=N` (and optionally `page[size]=N`) to API_URL and
    # advance until total-pages reached, an empty page, or MAX_PAGES.
    from urllib.parse import urlencode
    all_rows: list = []
    page = JSON_PAGE_START
    seen_pages = 0
    sep_first = "?" if "?" not in API_URL else "&"
    while seen_pages < JSON_MAX_PAGES:
        if JSON_PAGE_KIND == "offset":
            page_qs = {JSON_PAGE_PARAM: (page - JSON_PAGE_START) * JSON_PAGE_SIZE}
        else:
            page_qs = {JSON_PAGE_PARAM: page}
        if JSON_PAGE_SIZE_PARAM:
            page_qs[JSON_PAGE_SIZE_PARAM] = JSON_PAGE_SIZE
        url = API_URL + sep_first + urlencode(page_qs)
        sep_first = "&"  # subsequent pages always use '&'
        try:
            body = _http_get_bytes(url)
        except error.HTTPError as e:
            # Some publishers return 400 once an offset goes past the
            # advertised total (CMS Provider Data is one). Treat any
            # 4xx mid-walk as "done" if we already collected rows;
            # otherwise re-raise so the user sees the real error.
            if 400 <= getattr(e, "code", 500) < 500 and all_rows:
                break
            raise
        try:
            doc = json.loads(body)
        except Exception:
            break
        rows = _extract_json_records(doc)
        rows = _flatten_inner_records(rows) if isinstance(rows, list) else rows
        if not isinstance(rows, list) or not rows:
            break
        all_rows.extend(rows)
        seen_pages += 1
        # JSON:API style total-pages from meta.
        meta = doc.get("meta") if isinstance(doc, dict) else None
        if isinstance(meta, dict):
            tp = meta.get("total-pages") or meta.get("totalPages")
            if isinstance(tp, int) and page >= tp:
                break
        if len(rows) < JSON_PAGE_SIZE:
            break  # underfilled page = last page
        page += 1
    df = pd.DataFrame(all_rows) if all_rows else pd.DataFrame()
    return _apply_json_schema_coercion(df)


def _unwrap_json_records(rows):
    """Generic record-extractor: if a JSON response is wrapped in a
    common envelope key, return the inner list; otherwise pass through."""
    if isinstance(rows, dict):
        for key in ("results", "data", "items", "records", "rows"):
            if key in rows and isinstance(rows[key], list):
                return rows[key]
    return rows


def _flatten_inner_records(rows):
    """When JSON_FLATTEN_INNER_KEY is set, expand each parent record's
    inner list into one row per inner item, copying named parent
    fields onto every row. Used for response shapes like BLS where
    one parent (`series`) holds a list of monthly observations."""
    if not JSON_FLATTEN_INNER_KEY or not isinstance(rows, list):
        return rows
    out: list = []
    for parent in rows:
        if not isinstance(parent, dict):
            continue
        inner = parent.get(JSON_FLATTEN_INNER_KEY) or []
        if not isinstance(inner, list):
            continue
        carry = {k: parent.get(k) for k in JSON_FLATTEN_PARENT_KEYS if k in parent}
        for item in inner:
            if isinstance(item, dict):
                row = dict(carry)
                row.update(item)
                out.append(row)
    return out


def _extract_json_records(doc):
    """Resolve a JSON response to a list of record dicts. When
    JSON_RECORDS_PATH is set, walk the dotted path (numeric segments
    index into lists). Otherwise fall back to _unwrap_json_records.
    Used to pull a specific list out of nested envelopes that don't
    fit the standard 'results'/'data'/'items'/'records'/'rows' keys
    (e.g. BLS: 'Results.series.0.data')."""
    if not JSON_RECORDS_PATH:
        return _unwrap_json_records(doc)
    cur = doc
    for seg in JSON_RECORDS_PATH.split("."):
        if isinstance(cur, list):
            try:
                cur = cur[int(seg)]
            except (ValueError, IndexError):
                return cur
        elif isinstance(cur, dict):
            cur = cur.get(seg)
        else:
            return cur
        if cur is None:
            return []
    return cur


def _apply_json_schema_coercion(df: pd.DataFrame) -> pd.DataFrame:
    """Apply JSON_SCHEMA-driven type coercion to the raw fetched
    dataframe. JSON over the wire is all strings (or mixed strings +
    numbers + nulls); some publishers (e.g. Treasury Fiscal Data)
    serialize SQL NULLs as the literal string 'null', which pandas
    leaves in place as object dtype. Without this normalization,
    decimal/int columns reach Maestro as object and trigger
    'A decimal type is required for field [X]' rejections."""
    if df is None or len(df) == 0 or not JSON_SCHEMA:
        return df
    # 1) Sentinel nulls: lowercase 'null', empty string -> NaN. Done
    #    once across all object cols so downstream coercions see real NaN.
    sentinels = {"null", "Null", "NULL", "None", ""}
    obj_cols = [c for c in df.columns if df[c].dtype == "object"]
    for c in obj_cols:
        df[c] = df[c].where(~df[c].isin(sentinels), None)
    # 2) Synthesize derived columns from JSON_DERIVED_COLUMNS specs.
    #    Run BEFORE the column-keep trim so derived names are eligible.
    for derived in JSON_DERIVED_COLUMNS:
        try:
            name = derived.get("name")
            kind = derived.get("kind", "")
            if not name or kind == "":
                continue
            if kind == "year_month_iso":
                year_col = derived.get("year_col", "year")
                period_col = derived.get("period_col", "period")
                if year_col in df.columns and period_col in df.columns:
                    def _ym(yr, pr):
                        try:
                            yi = int(yr)
                            ps = str(pr or "")
                            if ps.startswith("M"):
                                m = int(ps[1:])
                            elif ps.startswith("Q"):
                                m = (int(ps[1:]) - 1) * 3 + 1
                            else:
                                m = int(ps)
                            if 1 <= m <= 12:
                                return f"{yi:04d}-{m:02d}-01"
                        except (TypeError, ValueError):
                            pass
                        return ""
                    df[name] = [_ym(y, p) for y, p in zip(df[year_col], df[period_col])]
            elif kind == "concat":
                cols = derived.get("cols", [])
                sep = derived.get("sep", "")
                if all(c in df.columns for c in cols):
                    df[name] = df[cols].astype(str).agg(sep.join, axis=1)
            elif kind == "list_join":
                # Flatten a list-valued column into a delimited string.
                # Useful for JSON sources that emit ['CWE-306', 'CWE-22']
                # — Maestro doesn't accept list-typed wire values.
                src_col = derived.get("source_col")
                sep = derived.get("sep", ", ")
                if src_col and src_col in df.columns:
                    df[name] = df[src_col].apply(
                        lambda v: sep.join(str(x) for x in v) if isinstance(v, list) else (str(v) if v is not None else "")
                    )
            elif kind == "list_first_field":
                # Pull a named field out of the first dict in a list-
                # valued column. Common need: APIs return
                # `agencies: [{name: 'X', ...}, ...]` — Tableau wants
                # a flat string. When the list is empty or non-dict,
                # fall back to empty string.
                src_col = derived.get("source_col")
                field = derived.get("field", "name")
                if src_col and src_col in df.columns:
                    def _first(v):
                        if isinstance(v, list) and v:
                            head = v[0]
                            if isinstance(head, dict):
                                return str(head.get(field, "") or "")
                        return ""
                    df[name] = df[src_col].apply(_first)
            elif kind == "days_since":
                # Calendar days from an ISO-date string column to today
                # (UTC). Useful for "days_since_filed", "days_open",
                # etc. in case-management style flows.
                src_col = derived.get("source_col")
                if src_col and src_col in df.columns:
                    s = pd.to_datetime(df[src_col], errors="coerce", utc=True)
                    now = pd.Timestamp.now(tz="UTC").normalize()
                    df[name] = (now - s).dt.days.fillna(0).astype("int64")
            elif kind == "days_between":
                # Calendar days between two ISO-date string columns.
                # Negative when the earlier column is later (rare in
                # SLA-style "added vs due" pairs).
                start_col = derived.get("start_col")
                end_col = derived.get("end_col")
                if start_col in df.columns and end_col in df.columns:
                    s = pd.to_datetime(df[start_col], errors="coerce")
                    e = pd.to_datetime(df[end_col], errors="coerce")
                    df[name] = (e - s).dt.days.fillna(0).astype("int64")
        except Exception:
            continue
    # 3) Drop any columns the publisher returned that aren't in the
    #    declared schema. Maestro's compile-time inspector matches the
    #    fetcher's actual output to get_output_schema(); extras are
    #    silently filtered upstream of downstream nodes, which can
    #    leave them empty if Maestro's schema-projection pass loses
    #    rows. Easier to align here.
    keep = list(JSON_SCHEMA.keys())
    df = df[[c for c in keep if c in df.columns]].copy()
    # 3) Apply per-column declared type from JSON_SCHEMA.
    for col, decl in JSON_SCHEMA.items():
        if col not in df.columns:
            continue
        d = (decl or "").lower()
        try:
            s = df[col]
            if d == "int":
                df[col] = pd.to_numeric(s, errors="coerce").fillna(0).astype("int64")
            elif d in ("decimal", "float", "double"):
                df[col] = pd.to_numeric(s, errors="coerce")
            elif d == "bool":
                df[col] = s.astype("bool")
            elif d in ("date", "datetime"):
                # Keep ISO 8601 string per the Maestro rule (Prep accepts
                # ISO strings under prep_date/prep_datetime). Don't
                # round-trip via pd.to_datetime; that creates Timestamp
                # objects which then mis-serialize through TabPy.
                df[col] = s.fillna("").astype(str)
            else:  # 'string' or unknown
                df[col] = s.fillna("").astype(str)
        except Exception:
            continue
    return df


def _fetch_arcgis_features() -> pd.DataFrame:
    """Format: arcgis_features.
    Query an ArcGIS REST FeatureServer/MapServer layer's /query endpoint,
    walk resultOffset pagination, flatten attributes + point geometry."""
    from urllib.parse import urlencode

    base = API_URL.rstrip("/")
    if not base.endswith("/query"):
        base = base + "/query"

    rows: list[dict] = []
    offset = 0
    while True:
        params = {
            "where": ARCGIS_WHERE,
            "outFields": ARCGIS_OUT_FIELDS,
            "f": "json",
            "returnGeometry": "true" if ARCGIS_RETURN_GEOMETRY else "false",
            "outSR": str(ARCGIS_OUT_SR),
            "resultOffset": str(offset),
            "resultRecordCount": str(ARCGIS_PAGE_SIZE),
        }
        url = base + "?" + urlencode(params)
        body = _http_get_bytes(url)
        data = json.loads(body.decode("utf-8", errors="replace"))
        if "error" in data:
            raise RuntimeError(f"ArcGIS error: {data['error']}")
        feats = data.get("features") or []
        if not feats:
            break
        for f in feats:
            attrs = dict(f.get("attributes") or {})
            geom = f.get("geometry") or {}
            # Point geometry: flatten x/y to lon/lat
            if "x" in geom and "y" in geom:
                attrs.setdefault("longitude", geom.get("x"))
                attrs.setdefault("latitude", geom.get("y"))
            # Polyline geometry: extract first and last vertex of the
            # first path as start/end endpoints. Sufficient for graph
            # edge tables where each line connects two stations.
            elif "paths" in geom and geom["paths"]:
                first_path = geom["paths"][0]
                if first_path:
                    sx, sy = first_path[0][0], first_path[0][1]
                    ex, ey = first_path[-1][0], first_path[-1][1]
                    attrs.setdefault("start_lon", sx)
                    attrs.setdefault("start_lat", sy)
                    attrs.setdefault("end_lon", ex)
                    attrs.setdefault("end_lat", ey)
            elif geom:
                attrs.setdefault("geometry_json", json.dumps(geom))
            rows.append(attrs)
        if ARCGIS_MAX_RECORDS and len(rows) >= ARCGIS_MAX_RECORDS:
            rows = rows[:ARCGIS_MAX_RECORDS]
            break
        # ArcGIS sets exceededTransferLimit when more pages remain
        if not data.get("exceededTransferLimit") and len(feats) < ARCGIS_PAGE_SIZE:
            break
        offset += len(feats)

    df = pd.DataFrame(rows)
    # ArcGIS epoch-millis timestamp fields → ISO 8601 strings.
    # We emit strings (not pd.Timestamp) because TabPy serializes the
    # response via json.dumps which can't handle Timestamp objects;
    # Tableau Prep + the script's `prep_string()` declaration both
    # happily accept the ISO string. The column MUST end up as pure
    # str dtype (not pandas object containing mixed Timestamp/None) -
    # Maestro 2026.1 inspects the wire dtype on the way in and rejects
    # the run with "A string type is required for [X]" if the column
    # is anything but a clean string series.
    # An explicit type override always wins over the name heuristic.
    # Without this, names like `ActiveFireCandidate` end with the
    # substring "date" and get coerced to ISO strings even when the
    # source already declares them as int.
    explicit = ARCGIS_FIELD_TYPES if FORMAT == "arcgis_features" else {}
    for col in df.columns:
        if col in explicit:
            continue
        lf = col.lower()
        # CamelCase columns like `FireDiscoveryDateTime` end in 'datetime',
        # but `ActiveFireCandidate` also ends in 'date' (substring of
        # 'Candidate'). Require an underscore boundary OR an exact
        # CamelCase tail (preceding char lowercase).
        is_date_col = False
        for suf in ("datetime", "date", "time", "_dt"):
            if lf.endswith(suf):
                if suf.startswith("_"):  # _dt
                    is_date_col = True
                    break
                # Boundary check: must be preceded by '_' or a
                # lowercase->uppercase camelcase transition.
                idx = len(lf) - len(suf)
                if idx == 0:
                    is_date_col = True
                    break
                prev_lower = lf[idx - 1]
                if prev_lower == "_":
                    is_date_col = True
                    break
                # CamelCase: preceding char in ORIGINAL was uppercase
                # break (e.g. `DiscoveryDate` - 'D' starts the suffix).
                # We approximate: require the original-case char at
                # position idx to be uppercase. Without this,
                # `Candidate` would still slip through.
                if idx < len(col) and col[idx].isupper():
                    is_date_col = True
                    break
        if not is_date_col:
            continue
        try:
            ts = pd.to_datetime(df[col], unit="ms", errors="coerce", utc=True)
            iso = ts.dt.strftime("%Y-%m-%dT%H:%M:%SZ")
            df[col] = iso.where(ts.notna(), "").astype(str)
        except Exception:
            try:
                df[col] = df[col].fillna("").astype(str)
            except Exception:
                pass
    return df


